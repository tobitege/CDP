using Microsoft.UI.Dispatching;
using Microsoft.UI.Xaml;

namespace CDP.Diagnostics.IntegrationTests;

internal static class WinUiTestHost
{
    internal static DispatcherQueue? Dispatcher { get; private set; }

    [STAThread]
    public static int Main(string[] args)
    {
        if (args.Any(arg => arg.Equals("-assemblyInfo", StringComparison.OrdinalIgnoreCase) ||
            arg.Equals("-list", StringComparison.OrdinalIgnoreCase) || arg is "-?" or "-help"))
        {
            return AutoGenerated.XunitAutoGeneratedEntryPoint.Main(args);
        }

        // WinUI owns the process's main STA thread. Run xUnit on a worker so
        // discovery and execution can use this already initialized dispatcher.
        try
        {
            Console.WriteLine("Starting the WinUI test application.");
            WinRT.ComWrappersSupport.InitializeComWrappers();
            Application.Start(initializationParameters =>
            {
                Dispatcher = DispatcherQueue.GetForCurrentThread();
                SynchronizationContext.SetSynchronizationContext(
                    new DispatcherQueueSynchronizationContext(Dispatcher));
                _ = new TestApplication(args);
            });
            Console.Error.WriteLine("The WinUI application loop exited before xUnit completed.");
        }
        catch (Exception exception)
        {
            Console.Error.WriteLine($"WinUI test application startup failed: {exception}");
        }
        return 1;
    }

    private sealed class TestApplication(string[] arguments) : Application
    {
        private Window? _hostWindow;

        protected override void OnLaunched(LaunchActivatedEventArgs args)
        {
            Console.WriteLine("The WinUI test application launched.");
            UnhandledException += (_, eventArgs) =>
                Console.Error.WriteLine($"Unhandled WinUI exception: {eventArgs.Exception}");
            // Create windows only after WinUI has launched. Keep a host window
            // alive until xUnit has written its results: closing the last test
            // window would otherwise end the application's message loop.
            _hostWindow = new Window { Content = new Microsoft.UI.Xaml.Controls.Grid() };
            _hostWindow.Activate();
            _ = Task.Run(RunTests);
        }

        private void RunTests()
        {
            var exitCode = 1;
            var output = Console.Out;
            var error = Console.Error;
            try
            {
                output.WriteLine("Starting xUnit with the WinUI dispatcher ready.");
                // This host owns shutdown; the console runner's static Run
                // helper starts a watchdog for foreground threads.
                using var runner = new Xunit.Runner.InProc.SystemConsole.ConsoleRunner(arguments);
                exitCode = runner.EntryPoint().GetAwaiter().GetResult();
            }
            catch (Exception exception)
            {
                error.WriteLine($"The WinUI xUnit runner failed: {exception}");
            }
            finally
            {
                output.Flush();
                error.Flush();
                GC.KeepAlive(_hostWindow);
                GC.KeepAlive(this);
                Environment.Exit(exitCode);
            }
        }
    }
}
