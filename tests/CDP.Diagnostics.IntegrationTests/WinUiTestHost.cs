using Microsoft.UI.Dispatching;
using Microsoft.UI.Xaml;

namespace CDP.Diagnostics.IntegrationTests;

internal static class WinUiTestHost
{
    internal static DispatcherQueue? Dispatcher { get; private set; }

    [STAThread]
    public static int Main(string[] args)
    {
        if (args.Any(arg => arg.Equals("-assemblyInfo", StringComparison.OrdinalIgnoreCase) ||
            arg.Equals("-list", StringComparison.OrdinalIgnoreCase) || arg is "-?" or "-help"))
        {
            return AutoGenerated.XunitAutoGeneratedEntryPoint.Main(args);
        }

        int exitCode = 1;
        // WinUI owns the process's main STA thread. Run xUnit on a worker so
        // discovery and execution can use this already initialized dispatcher.
        WinRT.ComWrappersSupport.InitializeComWrappers();
        Application.Start(_ =>
        {
            Dispatcher = DispatcherQueue.GetForCurrentThread();
            SynchronizationContext.SetSynchronizationContext(
                new DispatcherQueueSynchronizationContext(Dispatcher));
            var application = new Application();
            // Closing the last test window ends WinUI's application loop. Keep
            // a host window alive until xUnit has written all result messages.
            var hostWindow = new Window { Content = new Microsoft.UI.Xaml.Controls.Grid() };
            hostWindow.Activate();
            Dispatcher.TryEnqueue(() =>
            {
                Task.Run(() =>
                {
                    var output = Console.Out;
                    var error = Console.Error;
                    try
                    {
                        // This host owns shutdown; the console runner's static
                        // Run helper starts a watchdog for foreground threads.
                        using var runner = new Xunit.Runner.InProc.SystemConsole.ConsoleRunner(args);
                        exitCode = runner.EntryPoint().GetAwaiter().GetResult();
                    }
                    finally
                    {
                        output.Flush();
                        error.Flush();
                        GC.KeepAlive(hostWindow);
                        GC.KeepAlive(application);
                        Environment.Exit(exitCode);
                    }
                });
            });
        });
        return exitCode;
    }
}
